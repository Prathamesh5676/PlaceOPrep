const User = require('../models/User');
const Session = require('../models/Session');
const Submission = require('../models/Submission');
const Achievement = require('../models/Achievement');
const Skill = require('../models/Skill');

exports.downloadReport = async (req, res) => {
  try {
    const PDFDocument = require('pdfkit');

    const [user, sessions, submissions, achievements, skill] = await Promise.all([
      User.findById(req.userId).select('-password -refreshToken -resetPasswordToken'),
      Session.find({ userId: req.userId, completed: true }).sort({ createdAt: -1 }).limit(10),
      Submission.find({ userId: req.userId }).sort({ createdAt: -1 }).limit(10),
      Achievement.find({ userId: req.userId, unlocked: true }),
      Skill.findOne({ userId: req.userId })
    ]);

    if (!user) return res.status(404).json({ message: 'User not found' });

    const doc = new PDFDocument({ margin: 50 });
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="PlaceOPrep-Report-${user.name.replace(/\s+/g, '_')}.pdf"`);
    doc.pipe(res);

    // Header
    doc.rect(0, 0, doc.page.width, 80).fill('#7c3aed');
    doc.fillColor('white').fontSize(24).text('PlaceOPrep', 50, 25);
    doc.fontSize(12).text('Interview Preparation Report', 50, 55);
    doc.moveDown(3);

    // User Info
    doc.fillColor('#1f2937').fontSize(18).text(`${user.name}`, 50, 100);
    doc.fontSize(11).fillColor('#6b7280').text(`${user.email}`, 50, 122);
    doc.text(`Report generated: ${new Date().toLocaleDateString()}`, 50, 138);

    // Stats
    doc.moveDown(2);
    doc.fillColor('#1f2937').fontSize(16).text('Performance Overview', 50, doc.y);
    doc.moveDown(0.5);

    const stats = [
      ['Total Interviews', user.totalInterviews || 0],
      ['Average Score', `${user.averageScore || 0}%`],
      ['Best Score', `${user.bestScore || 0}%`],
      ['Practice Time', `${Math.round((user.practiceTime || 0) / 60)} hrs`],
      ['Current Streak', `${user.currentStreak || 0} days`]
    ];

    stats.forEach(([label, value]) => {
      doc.fontSize(11).fillColor('#374151').text(`${label}: `, { continued: true });
      doc.fillColor('#7c3aed').text(`${value}`);
    });

    // Skills
    if (skill) {
      doc.moveDown(1);
      doc.fillColor('#1f2937').fontSize(16).text('Skill Levels');
      doc.moveDown(0.5);
      const skillItems = [
        ['Technical', skill.technical || 0],
        ['HR / Communication', skill.hr || 0],
        ['Aptitude', skill.aptitude || 0],
        ['Communication', skill.communication || 0]
      ];
      skillItems.forEach(([label, score]) => {
        doc.fontSize(11).fillColor('#374151').text(`${label}: ${score}/100`);
      });
    }

    // Achievements
    if (achievements.length > 0) {
      doc.moveDown(1);
      doc.fillColor('#1f2937').fontSize(16).text('Unlocked Achievements');
      doc.moveDown(0.5);
      achievements.forEach(a => {
        doc.fontSize(10).fillColor('#374151').text(`${a.icon || '★'} ${a.name} — ${a.description}`);
      });
    }

    // Recent Sessions
    if (sessions.length > 0) {
      doc.moveDown(1);
      doc.fillColor('#1f2937').fontSize(16).text('Recent Sessions');
      doc.moveDown(0.5);
      sessions.forEach(s => {
        const date = new Date(s.createdAt).toLocaleDateString();
        doc.fontSize(10).fillColor('#374151')
          .text(`${date} — ${s.type} (${s.difficulty || 'N/A'}) — Score: ${s.score}%`);
      });
    }

    // Footer
    const pageHeight = doc.page.height;
    doc.rect(0, pageHeight - 40, doc.page.width, 40).fill('#f3f4f6');
    doc.fillColor('#6b7280').fontSize(9).text('Generated by PlaceOPrep | placeoprep.app', 50, pageHeight - 25);

    doc.end();
  } catch (error) {
    res.status(500).json({ message: 'Server error', error: error.message });
  }
};
